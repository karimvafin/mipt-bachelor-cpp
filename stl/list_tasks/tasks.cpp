// Удалите все чётные элементы из списка in-place.
// В отличие от std::vector, удаление из std::list не инвалидирует итераторы
// на другие элементы — воспользуйтесь этим.
// Пример: l = {1, 2, 3, 4, 5}  ->  l = {1, 3, 5}
// Пример: l = {2, 4, 6}        ->  l = {}
// -----------------------------------------------------------------------------
void remove_if_even(std::list<int>& l) {
   auto real_position= l.begin();
    while(real_position != l.end ())
    {
        if(*real_position%2==0)
        {
           real_position=l.erase(real_position);
        }
        else
            real_position++;
    } 
}

