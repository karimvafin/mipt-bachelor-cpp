// -----------------------------------------------------------------------------
// Задание 1: sum (0.25 баллов)
// Посчитайте сумму всех элементов списка.
// Пример: sum({1, 2, 3, 4}) == 10
// Пример: sum({}) == 0
// -----------------------------------------------------------------------------
int sum(const std::list<int>& l) {
    int sum=0;
    auto real_position= l.begin();
    while(real_position != l.end ())
    {
        sum=sum+*real_position;
        real_position++;
    } 
    return sum;
}

