// Задание 5: is_palindrome (0.5 баллов)
// Проверьте, является ли список палиндромом.
// Пример: is_palindrome({1, 2, 3, 2, 1}) == true
// Пример: is_palindrome({1, 2, 3})       == false
// Пример: is_palindrome({})              == true
// Пример: is_palindrome({7})             == true
// Подсказка: у std::list нет произвольного доступа — подумайте,
// как сравнить элементы с обоих концов.
// -----------------------------------------------------------------------------
bool is_palindrome(const std::list<int>& l) {
    if (l.size() <= 1) {
        return true;
    }
    
    auto left = l.begin();
    auto right = l.end();
    --right;
    
    while (left != right && std::next(left) != right) {
        if (*left != *right) {
            return false;
        }
        ++left;
        --right;
    }
    
    if (left != right && *left != *right) {
        return false;
    }
    
    return true;
}
