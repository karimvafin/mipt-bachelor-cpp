// -----------------------------------------------------------------------------
// Задание 1: sum (0.25 баллов)
// Посчитайте сумму всех элементов списка.
// Пример: sum({1, 2, 3, 4}) == 10
// Пример: sum({}) == 0
// -----------------------------------------------------------------------------
int sum(const std::list<int>& l) {
    auto it = l.begin();
    int res = 0;
    for(it; it!=l.end(); ++it){
        res+= *it;
    }
    return res;
}

