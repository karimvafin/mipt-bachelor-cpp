// Задание 4: interleave (0.25 баллов)
// Перемежайте элементы двух списков в список a: сначала элемент из a,
// затем элемент из b, и так далее. Если один список длиннее — оставшиеся
// элементы дописываются в конец.
// После вызова список b должен быть пустым.
// Пример: a = {1, 3, 5}, b = {2, 4}      ->  a = {1, 2, 3, 4, 5},   b = {}
// Пример: a = {1},        b = {2, 3, 4}   ->  a = {1, 2, 3, 4},      b = {}
// Подсказка: используйте splice — он переносит элементы без копирования.
// -----------------------------------------------------------------------------
void interleave(std::list<int>& a, std::list<int>& b) {
    auto pos_a = a.begin();
    while (!b.empty()) {
    if (pos_a == a.end()) {
            a.splice(a.end(), b);  
            break;
        }
    }
        pos_a++;
        a.splice(pos_a, b, b.begin());
}

